/*
 * sanitizer-shim: default options, leak-check hook and per-binary controls
 * for the GCC sanitizer runtimes (libasan, liblsan code inside libasan,
 * libubsan) on glibc.
 *
 * Preloaded alone through /etc/ld.so.preload into every process:
 *
 *   /usr/lib/libsanitizer-shim.so
 *
 * Instrumented binaries load libasan and libubsan through DT_NEEDED;
 * uninstrumented ones never get them, and the shim stays inert there.
 *
 * 1. __asan_default_options(), __lsan_default_options() and
 *    __ubsan_default_options() return constant strings built from the
 *    SHIM_* macros (Kconfig). libasan exports weak empty versions of the
 *    first two; the first definition in the lookup order wins, and a
 *    preloaded object comes before every DT_NEEDED library. The ASan
 *    string sets verify_asan_link_order=0: that check wants libasan first
 *    and runs after the flags are parsed. Called during runtime init: no
 *    malloc, no stdio. The shim defines no function that libasan
 *    intercepts.
 * 2. SIGRTMIN+SHIM_LEAK_SIGNAL_OFFSET triggers
 *    __lsan_do_recoverable_leak_check() and __sanitizer_print_memory_profile()
 *    in a helper thread. The handler only does sem_post() (async-signal-safe).
 * 3. __lsan_is_turned_off() returns 1 if SHIM_OFF_DIR/<exe basename> (tmpfs,
 *    runtime) or SHIM_OFF_DIR_STATIC/<exe basename> (shipped) exists.
 * 4. The directory of log_path is created (mkdir -p, leaf 1777) with raw
 *    syscalls from the default-options functions, which run before
 *    sanitizer_common sets up the report path. GCC 13 libsanitizer creates
 *    missing parents itself with mode 0755 and calls Die() if it cannot, so
 *    a non-root process could not write into a directory root made later.
 *    If that directory is not writable (read-only root during preinit), the
 *    reports go to stderr (a report file that cannot be opened makes
 *    libsanitizer exit the process), and item 5 copies them to the console.
 *    No report is kept only in RAM (tmpfs).
 * 5. __sanitizer_report_error_summary() (weak in libasan and libubsan,
 *    called once per report) writes one console line per report,
 *    "SANREPORT <exe> <pid> <type> <file>". ASan and LSan summaries are
 *    passed on to libasan's own copy, which prints the SUMMARY line into
 *    the report. UBSan summaries are not printed: libubsan's call would
 *    bind to libasan's copy and put the line into the ASan report file.
 *    UBSan needs print_summary=1 for the call at all (its default is 0).
 *    __sanitizer_on_print() (a weak no-op, called for every printed
 *    chunk) copies the reports to /dev/console while they go to stderr,
 *    unless stderr is a terminal already. The QEMU serial console thus
 *    keeps the reports and an index of them on the host.
 * 6. The ASan quarantine is sized by the guest RAM (MemTotal, read with raw
 *    syscalls: __asan_default_options() runs before the allocator), from
 *    the Kconfig tier table, and soft_rss_limit_mb is MemTotal / divisor.
 *    A process over the soft limit fails its next allocation with an
 *    out-of-memory report and its allocation stack (fatal also with
 *    halt_on_error=0), instead of the OOM killer taking a random process.
 *    The quarantine size of a running process cannot be changed.
 *    /etc/sanitizer/<binary>.opts still overrides both.
 *
 * This file must be built WITHOUT sanitizers and must not link libasan.
 */
