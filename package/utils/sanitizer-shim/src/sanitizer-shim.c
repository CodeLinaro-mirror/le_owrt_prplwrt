/*
 * Option strings. Each flag appears only in the parser that knows it:
 *  - ASan parser (asan flags + common flags): halt_on_error, verify_asan_link_order,
 *    and the common flags symbolize, log_path, log_exe_name, detect_leaks.
 *    The common flags are one global set inside libasan, so LSan needs no copy.
 *  - LSan parser (lsan flags + common flags): suppressions (leak: patterns).
 *    NOT given to ASan: its own "suppressions" flag takes interceptor
 *    suppressions and would reject "leak:" lines.
 *  - UBSan runs in libubsan.so with its own flag set (print_stacktrace,
 *    halt_on_error) and its own copy of the common flags. log_suffix keeps
 *    its file apart from ASan's: both runtimes open <log_path>.<exe>.<pid>
 *    with O_TRUNC and would overwrite each other.
 * The include comes last in each string, so a per-binary file overrides
 * the defaults above it; the environment overrides everything.
 * A %b.opts file is read by every parser it is included from, so it must
 * not contain "suppressions=" (the three parsers read it differently).
 */
#define COMMON_OPTS(path)                                                   \
	"symbolize=" STR(SHIM_SYMBOLIZE) ":log_path=" path                  \
	":log_exe_name=1"

/* The memory tier (item 6) goes between the head and the tail. */
#define ASAN_OPTS_HEAD(path)                                                \
	"halt_on_error=" STR(SHIM_HALT_ON_ERROR) ":"                        \
	"verify_asan_link_order=0:" COMMON_OPTS(path)                       \
	":detect_leaks=" STR(SHIM_DETECT_LEAKS)

#define ASAN_OPTS_TAIL                                                      \
	":" SHIM_EXTRA_ASAN_OPTS ":include_if_exists=" SHIM_OPTS_INCLUDE

#define LSAN_TAIL_STR                                                       \
	SHIM_EXTRA_LSAN_OPTS ":include_if_exists=" SHIM_OPTS_INCLUDE

#define UBSAN_OPTS_STR(path)                                                \
	"halt_on_error=" STR(SHIM_HALT_ON_ERROR) ":print_stacktrace="       \
	STR(SHIM_UBSAN_PRINT_STACKTRACE) ":" COMMON_OPTS(path)              \
	":print_summary=1:report_error_type=1"                              \
	":log_suffix=" SHIM_UBSAN_LOG_SUFFIX ":" SHIM_EXTRA_UBSAN_OPTS ":include_if_exists=" SHIM_OPTS_INCLUDE

/* UBSan reads "<check>:<module|file|function>" lines, e.g. pointer-overflow:busybox */
#define UBSAN_SUPP_STR ":suppressions=" SHIM_UBSAN_SUPPRESSIONS

/* ---- raw syscall helpers (no libc state, no malloc, no interceptors) -- */

static int sys_access(const char *path)
{
	return syscall(SYS_faccessat, AT_FDCWD, path, F_OK) == 0;
}

/* Suppression files: the runtimes die if they cannot read them. */
static int sys_readable(const char *path)
{
	return syscall(SYS_faccessat, AT_FDCWD, path, R_OK) == 0;
}

static size_t slen(const char *s)
{
	size_t n = 0;

	while (s[n])
		n++;
	return n;
}

/*
 * Writable means a file can really be created, with the effective IDs and
 * the mount flags: faccessat() without AT_EACCESS checks the real UID.
 * dir has length len and room for the probe name in a 256-byte buffer.
 */
static int dir_writable(char *dir, size_t len)
{
	static const char probe[] = "/.shim-probe.";
	unsigned long pid = syscall(SYS_getpid);
	char tmp[24];
	size_t i, n = 0, end;
	long fd;

	if (len + sizeof(probe) + sizeof(tmp) >= 256)
		return 0;
	for (i = 0; probe[i]; i++)
		dir[len + i] = probe[i];
	end = len + i;
	do
		tmp[n++] = '0' + pid % 10;
	while ((pid /= 10) && n < sizeof(tmp));
	while (n)
		dir[end++] = tmp[--n];
	dir[end] = '\0';
	fd = syscall(SYS_openat, AT_FDCWD, dir,
		     O_WRONLY | O_CREAT | O_APPEND | O_CLOEXEC, 0600);
	if (fd >= 0) {
		syscall(SYS_close, fd);
		syscall(SYS_unlinkat, AT_FDCWD, dir, 0);
	}
	dir[len] = '\0';
	return fd >= 0;
}

/*
 * Create the directory part of a log_path prefix, like mkdir -p.
 * Returns 1 if the directory is writable afterwards.
 */
static int ensure_log_dir(const char *prefix)
{
	char buf[256];
	size_t n = slen(prefix), i;
	int saved = errno, ok = 0;

	if (prefix[0] != '/' || n >= sizeof(buf))
		return 0;
	for (i = 0; i < n; i++)
		buf[i] = prefix[i];
	buf[n] = '\0';
	while (n > 1 && buf[n - 1] != '/')
		n--;
	if (n <= 1)
		return 0;
	buf[n - 1] = '\0'; /* directory only */
	n--;

	if (syscall(SYS_mkdirat, AT_FDCWD, buf, 01777) != 0) {
		if (errno == EEXIST)
			goto out;
		for (i = 1; i < n; i++) {
			if (buf[i] != '/')
				continue;
			buf[i] = '\0';
			syscall(SYS_mkdirat, AT_FDCWD, buf, 0755);
			buf[i] = '/';
		}
		if (syscall(SYS_mkdirat, AT_FDCWD, buf, 01777) != 0)
			goto out;
	}
	/* Daemons run as different users; make the leaf writable for all. */
	syscall(SYS_fchmodat, AT_FDCWD, buf, 01777, 0);
out:
	ok = dir_writable(buf, n);
	errno = saved;
	return ok;
}

/* 0: SHIM_LOG_PATH, 1: stderr (copied to the console) */
static int g_log_choice;

static int log_choice(void)
{
	g_log_choice = ensure_log_dir(SHIM_LOG_PATH) ? 0 : 1;
	return g_log_choice;
}

